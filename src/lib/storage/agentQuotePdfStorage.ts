/**
 * Confidential, immutable Agent Proposal PDFs.
 * Never write generated agency proposals under public/ in production.
 * Only the authenticated quote PDF endpoint may stream these files.
 */
import { randomUUID } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { get, put } from "@vercel/blob";

const PRIVATE_PREFIX = "private-agent-pdf:";

function hasBlobAuthentication() {
  return Boolean(process.env.VERCEL_OIDC_TOKEN?.trim() || process.env.BLOB_READ_WRITE_TOKEN?.trim());
}
function onVercel() {
  return Boolean(process.env.VERCEL || process.env.VERCEL_URL || process.env.VERCEL_REGION);
}
function safeQuoteId(quoteId: string) {
  if (!/^[a-zA-Z0-9_-]{4,100}$/.test(quoteId)) throw new Error("Invalid quote identifier for PDF storage.");
  return quoteId;
}
function isPrivateBlobUrl(value: string) {
  try {
    const url = new URL(value);
    return url.protocol === "https:" &&
      (url.hostname === "private.blob.vercel-storage.com" || url.hostname.endsWith(".private.blob.vercel-storage.com"));
  } catch { return false; }
}
function localFile(quoteId: string, fileId: string) {
  return path.join(process.cwd(), ".private", "agent-proposals", quoteId, `${fileId}.pdf`);
}

export async function savePrivateAgentQuotePdf(quoteId: string, bytes: Buffer): Promise<string> {
  const id = safeQuoteId(quoteId);
  if (!bytes.length || bytes.subarray(0, 5).toString() !== "%PDF-") {
    throw new Error("Generated agent proposal is not a valid PDF.");
  }
  const fileId = randomUUID();
  if (hasBlobAuthentication()) {
    const blob = await put(`agent-proposals/${id}/${fileId}.pdf`, bytes, {
      access: "private",
      addRandomSuffix: false,
      contentType: "application/pdf",
    });
    return blob.url;
  }
  if (onVercel()) {
    throw new Error("Private Vercel Blob storage is not configured for the agent proposal. Check the Blob connection.");
  }
  // Persistent developer-machine storage, outside public/.
  const filePath = localFile(id, fileId);
  await mkdir(path.dirname(filePath), { recursive: true, mode: 0o700 });
  await writeFile(filePath, bytes, { mode: 0o600 });
  return `${PRIVATE_PREFIX}${id}:${fileId}`;
}

export async function readPrivateAgentQuotePdf(storagePath: string, quoteId: string): Promise<Buffer | null> {
  const id = safeQuoteId(quoteId);
  if (isPrivateBlobUrl(storagePath)) {
    if (!hasBlobAuthentication()) throw new Error("Private Blob access is not configured.");
    const blob = await get(storagePath, { access: "private" });
    if (!blob || blob.statusCode !== 200 || !blob.stream) return null;
    return Buffer.from(await new Response(blob.stream).arrayBuffer());
  }
  if (storagePath.startsWith(PRIVATE_PREFIX)) {
    const localMatch = /^private-agent-pdf:([a-zA-Z0-9_-]{4,100}):([0-9a-f-]{36})$/.exec(storagePath);
    if (!localMatch || localMatch[1] !== id) return null;
    return await readFile(localFile(id, localMatch[2])).catch(() => null);
  }
  // Legacy local PDFs generated by the old route. The stored paths are
  // restricted to an exact basename. Deployed public files are not secure;
  // this compatibility path is read-only and should not be used for new files.
  if (/^\/agent-client-quotes\/[a-zA-Z0-9._-]+\.pdf$/.test(storagePath)) {
    return await readFile(path.join(process.cwd(), "public", storagePath.slice(1))).catch(() => null);
  }
  return null;
}
